-- Schools ask to join, and the site owner approves each one by hand.
CREATE TABLE school_request (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_name  TEXT NOT NULL,
  contact_name TEXT NOT NULL,
  phone        TEXT NOT NULL,
  email        TEXT,
  town         TEXT NOT NULL,
  lang         TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','declined')),
  school_id    INTEGER REFERENCES school(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL,
  decided_at   TEXT
);
CREATE INDEX school_request_status ON school_request(status, created_at);

-- Set only by a sign-in that proved one of the owner's email addresses.
ALTER TABLE session ADD COLUMN owner_email TEXT;
